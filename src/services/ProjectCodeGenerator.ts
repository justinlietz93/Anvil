import { Project, ComponentInstance } from '../contexts/ProjectContext';

export interface GeneratedFiles {
  indexHtml: string;
  stylesCss: string;
  appJs: string;
}

/**
 * ProjectCodeGenerator.generateWebAppFiles()
 * Generates a minimal, self-contained web app (HTML/CSS/JS) from the current Project model.
 * - Absolute positioning based on component.styles (left, top, width, height)
 * - Basic components mapped to native HTML equivalents for portability
 * - Embeds project and blueprints into window.Anvil for simple runtime access
 * - Provides a mock LLM stub for demonstration in exported builds
 */
export function generateWebAppFiles(project: Project): GeneratedFiles {
  const bodyContent = renderProjectComponents(project);
  const indexHtml = generateIndexHtml(project, bodyContent);
  const stylesCss = generateStylesCss();
  const appJs = generateAppJs(project);
  return { indexHtml, stylesCss, appJs };
}

function generateIndexHtml(project: Project, bodyContent: string): string {
  const appTitle = escapeHtml(project?.metadata?.name || 'Anvil App');
  const appDescription = escapeHtml(project?.metadata?.description || 'An application generated by Anvil');

  return [
    '<!DOCTYPE html>',
    '<html lang="en">',
    '  <head>',
    '    <meta charset="UTF-8" />',
    '    <meta name="viewport" content="width=device-width, initial-scale=1.0" />',
    `    <title>${appTitle}</title>`,
    '    <link rel="stylesheet" href="styles.css" />',
    '  </head>',
    '  <body>',
    '    <div class="app-container">',
    `      <header class="app-header"><h1>${appTitle}</h1><p>${appDescription}</p></header>`,
    '      <main class="app-main" id="app-root">',
    bodyContent,
    '      </main>',
    '    </div>',
    '    <script src="app.js"></script>',
    '  </body>',
    '</html>',
    ''
  ].join('\n');
}

